export type TranslationKey = keyof typeof translations.en;

export function translate(language: Language, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function translateStatus(language: Language, value: string): string {
  const key = `status.${value}`;
  const table = translations[language] as Record<string, string>;
  const fallback = translations.en as Record<string, string>;
  return table[key] ?? fallback[key] ?? value;
}

export function loadLanguage(): Language {
  const stored = globalThis.localStorage?.getItem('routefast.language');
  if (stored === 'es' || stored === 'en') return stored;
  return globalThis.navigator?.language?.toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function persistLanguage(language: Language): void {
  globalThis.localStorage?.setItem('routefast.language', language);
}
